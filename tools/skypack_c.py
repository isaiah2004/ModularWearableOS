"""skypack_c.py - the sky pack for the watch: C tables in flash plus two SD files.

Reads the JSON snapshot tools/skypack.py writes (docs/assets/solar/atlas.js) and emits
  nos/faces/orrery_data.c   small tables in flash: named small bodies, comets near perihelion,
                            spacecraft, Earth flybys, the pack date, the belt / moon counts
  belt.bin, moons.bin       the two big catalogs (4000 brightest asteroids, every known moon), written to
                            assets/sd/sky/ (tracked) and staged into build/sd/sky/ (the local SD mirror
                            that tools/sdsync.py pushes to <sd>/sky/)
Layout, little endian: 48-byte header = magic[4], u16 version, u16 header bytes, u32 count, u32 record
bytes, u32 payload bytes, u32 CRC32 of the payload, f64 pack JD, char built[16]; then the payload.
  belt.bin   'ORBL': count x od_ast (7 f32 + i8 H x 10, padded to 32 B)
  moons.bin  'ORMN': 11 x {u32 byte offset, u32 count} per planet (EP_* index, 10 = Pluto), then count x
             od_moon (name[16], i8 planet, u8 fresh, u16 pad, u32 code, 8 f64 = 88 B) grouped by planet

usage: python tools/skypack_c.py [--atlas docs/assets/solar/atlas.js] [--out nos/faces/orrery_data.c]
                                 [--sd-out assets/sd/sky] [--stage build/sd/sky | --no-stage]"""
import argparse, json, os, shutil, struct, zlib
from fractions import Fraction

ap = argparse.ArgumentParser()
ap.add_argument('--atlas', default='docs/assets/solar/atlas.js')
ap.add_argument('--out', default='nos/faces/orrery_data.c')
ap.add_argument('--sd-out', default='assets/sd/sky')
ap.add_argument('--stage', default='build/sd/sky')
ap.add_argument('--no-stage', action='store_true')
A = ap.parse_args()
s = open(A.atlas, encoding='utf-8').read()
d = json.loads(s[s.index('{'):s.rindex('}') + 1])

PL = {'mercury': 0, 'venus': 1, 'earth': 2, 'mars': 3, 'jupiter': 4, 'saturn': 5, 'uranus': 6, 'neptune': 7, 'pluto': 10, None: -1}
KIND = {'asteroid': 0, 'dwarf': 1, 'kbo': 2, 'comet': 3, 'interstellar': 4}


def cs(x):
    return '"' + str(x).replace('\\', '\\\\').replace('"', '\\"') + '"'


def f(x, p=6):
    return ('%.' + str(p) + 'g') % float(x) + ('' if '.' in ('%.' + str(p) + 'g') % float(x) or 'e' in ('%.' + str(p) + 'g') % float(x) else '.0')


def f32(text):
    """the float a C compiler makes of the decimal literal `text` (round to nearest even, no double rounding)"""
    x, v = Fraction(text), float(text)
    c = struct.unpack('<f', struct.pack('<f', v))[0]
    best, bd = c, abs(Fraction(c) - x)
    for b in (struct.unpack('<I', struct.pack('<f', c))[0] + k for k in (-1, 1)):
        n = struct.unpack('<f', struct.pack('<I', b & 0xffffffff))[0]
        if n != n or n in (float('inf'), float('-inf')): continue
        dn = abs(Fraction(n) - x)
        if dn < bd or (dn == bd and b % 2 == 0): best, bd = n, dn
    return best


def sd_file(magic, count, recsz, payload, d):
    head = struct.pack('<4sHHIIIId16s', magic, 1, 48, count, recsz, len(payload), zlib.crc32(payload) & 0xffffffff,
                       float('%.1f' % d['jd']), d['built'].encode('ascii'))
    assert len(head) == 48
    return head + payload


L = ['/* orrery_data.c - generated by tools/skypack_c.py from the sky pack built %s. Do not edit.' % d['built'],
     ' * Sources: NASA/JPL SSD (SBDB, satellite mean elements, Horizons, CAD). The belt and moon catalogs are not here:',
     ' * they are the SD files sky/belt.bin and sky/moons.bin written by the same script. */',
     '#include "faces/orrery_data.h"', '',
     'const double od_pack_jd = %.1f;' % d['jd'], 'const char od_built[] = %s;' % cs(d['built']), '']

# a, e, i, node, w (au, deg), M at epoch (deg), epoch - 2451545 (days), H x 10
belt = bytearray()
for r in d['belt']:
    a, e, i, om, w, ma, ep, H = r
    v = [f32(f(a)), f32(f(e)), f32(f(i)), f32(f(om)), f32(f(w)), f32(f(ma)), f32(f(ep - 2451545.0, 9))]
    belt += struct.pack('<7fb3x', *v, round(H * 10))
L.append('const int od_belt_n = %d;   /* rows in sky/belt.bin */' % len(d['belt']))
L.append('')

L.append('const od_small od_small_bodies[] = {')
for o in d['small']:
    L.append('    { %s, %s, %d, { %s, %s, %s, %s, %s, %s }, %sf },' % (
        cs(o['name']), cs(o.get('short') or o['name']), KIND[o['kind']], f(o['e'], 9), f(o['q'], 9), f(o['i'], 9), f(o['node'], 9),
        f(o['w'], 9), f(o['tp'], 12), f(o['diam'] or 0)))
L.append('};')
L.append('const int od_small_n = %d;' % len(d['small']))
L.append('')

L.append('const od_comet od_comets[] = {')
for o in d['comets']:
    L.append('    { %s, { %s, %s, %s, %s, %s, %s }, %sf },' % (
        cs(o['name']), f(o['e'], 9), f(o['q'], 9), f(o['i'], 9), f(o['node'], 9), f(o['w'], 9), f(o['tp'], 12),
        f(o['M1'] if o['M1'] is not None else 99)))
L.append('};')
L.append('const int od_comets_n = %d;' % len(d['comets']))
L.append('')

L.append('const od_craft od_crafts[] = {')
for c in d['craft']:
    o = c.get('orbit')
    orb = '{ %s, %s, %s, %s, %s, %s, %s, %s }' % (f(o['a'], 9), f(o['e'], 9), f(o['i'], 9), f(o['node'], 9), f(o['w'], 9),
                                                   f(o['M'], 9), f(o['P'], 9), f(o['epoch'], 12)) if o else '{ 0, 0, 0, 0, 0, 0, 0, 0 }'
    xyz = c.get('xyz') or [0, 0, 0]
    L.append('    { %s, %d, %s, { %s, %s, %s }, %d, %s },' % (cs(c['name']), PL[c['planet']], cs(c['status']),
                                                            f(xyz[0], 9), f(xyz[1], 9), f(xyz[2], 9), 1 if o else 0, orb))
L.append('};')
L.append('const int od_crafts_n = %d;' % len(d['craft']))
L.append('')

# every known moon, grouped by planet (stable), with a per-planet {byte offset, count} index
moons = sorted(d['moons'], key=lambda m: PL[m['planet']])
HEAD, IDX, REC = 48, 11 * 8, 88
cnt = [0] * 11
recs = bytearray()
for m in moons:
    nm = m['name'].encode('ascii')
    assert len(nm) <= 15, m['name']
    cnt[PL[m['planet']]] += 1
    recs += struct.pack('<16sbBHI8d', nm, PL[m['planet']], 1 if m.get('fresh') else 0, 0, m['code'],
                        float(f(m['a'], 9)), float(f(m['e'] or 0, 9)), float(f(m['i'] or 0, 9)), float(f(m['node'] or 0, 9)),
                        float(f(m['w'] or 0, 9)), float(f(m['M'] or 0, 9)), float(f(m['P'], 9)), float(f(m['epoch'], 12)))
assert len(recs) == REC * len(moons)
index, off = bytearray(), HEAD + IDX
for c in cnt:
    index += struct.pack('<II', off, c)
    off += c * REC
L.append('const int od_moons_n = %d;   /* rows in sky/moons.bin */' % len(moons))
L.append('const uint16_t od_moon_count[OD_PLANETS] = { %s };' % ', '.join(str(c) for c in cnt))
L.append('')

L.append('const od_flyby od_flybys[] = {')
for fl in d['flybys']:
    L.append('    { %s, %s, %sf, %sf, %sf },' % (cs(fl['des']), f(fl['jd'], 12), f(fl['au']), f(fl['kms']), f(fl['H'] or 0)))
L.append('};')
L.append('const int od_flybys_n = %d;' % len(d['flybys']))
open(A.out, 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')

files = {'belt.bin': sd_file(b'ORBL', len(d['belt']), 32, bytes(belt), d),
         'moons.bin': sd_file(b'ORMN', len(moons), REC, bytes(index + recs), d)}
dests = [A.sd_out] + ([] if A.no_stage else [A.stage])
for dest in dests:
    os.makedirs(dest, exist_ok=True)
    for name, data in files.items():
        with open(os.path.join(dest, name), 'wb') as out: out.write(data)
print('wrote', A.out, 'belt', len(d['belt']), 'small', len(d['small']), 'comets', len(d['comets']), 'craft', len(d['craft']),
      'moons', len(moons), 'flybys', len(d['flybys']))
for name, data in files.items(): print('wrote', ', '.join(os.path.join(x, name) for x in dests), len(data), 'bytes')
