"""Bake an animated GIF into an RGB565 sprite sheet C array for the watch.

Usage: python bake_sprite.py <in.gif> <c_name> <size> <nframes>
Samples `nframes` frames evenly from the GIF, resizes to size x size,
composites transparency onto black, and emits core/<c_name>.c/.h.
"""
import os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "core")


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def bake(path, name, size, nframes):
    im = Image.open(path)
    total = im.n_frames
    frames = []
    for i in range(nframes):
        im.seek(round(i * total / nframes) % total)
        fr = im.convert("RGBA").resize((size, size), Image.LANCZOS)
        bg = Image.new("RGBA", (size, size), (0, 0, 0, 255))
        fr = Image.alpha_composite(bg, fr).convert("RGB")
        px = list(fr.getdata())
        frames.append([rgb565(*p) for p in px])

    cpath = os.path.join(OUT, name + ".c")
    hpath = os.path.join(OUT, name + ".h")
    with open(hpath, "w") as f:
        f.write("#ifndef WATCH_%s_H\n#define WATCH_%s_H\n#include <stdint.h>\n"
                % (name.upper(), name.upper()))
        f.write("#define %s_SIZE %d\n#define %s_FRAMES %d\n"
                % (name.upper(), size, name.upper(), nframes))
        f.write("extern const uint16_t %s[%d][%d];\n#endif\n"
                % (name, nframes, size * size))
    with open(cpath, "w") as f:
        f.write('#include "%s.h"\n' % name)
        f.write("/* generated by tools/bake_sprite.py from %s */\n"
                % os.path.basename(path))
        f.write("const uint16_t %s[%d][%d] = {\n" % (name, nframes, size * size))
        for fr in frames:
            f.write("{")
            f.write(",".join(str(v) for v in fr))
            f.write("},\n")
        f.write("};\n")
    kb = nframes * size * size * 2 / 1024
    print("%s: %d frames %dx%d -> %.0f KB (%s)" % (name, nframes, size, size, kb, cpath))


if __name__ == "__main__":
    _, path, name, size, nframes = sys.argv
    bake(path, name, int(size), int(nframes))
