"""Build the two static, ASCII-only Ultra fonts (requires fonttools).

Source: assets/Saira-Variable.ttf; license: assets/Saira-OFL.txt.
Run from any directory with: python tools/bake_ultra_fonts.py
The firmware reads these static instances directly with stb_truetype.
"""
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]


def bake(name, symbol, weight, width):
    font = TTFont(ROOT / "assets/Saira-Variable.ttf", recalcTimestamp=False)
    instantiateVariableFont(font, {"wght": weight, "wdth": width},
                            inplace=True, updateFontNames=True)
    options = subset.Options()
    options.recalc_timestamp = False
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=range(32, 127))
    sub.subset(font)
    assert "fvar" not in font and "gvar" not in font
    target = ROOT / f"assets/{name}.ttf"
    font.save(target)
    data = target.read_bytes()
    guard = f"WATCH_FONT_{symbol.upper()}_H"
    lines = [f"/* Generated by tools/bake_ultra_fonts.py; Saira, SIL OFL 1.1.",
             f" * Static wght={weight}, wdth={width}; ASCII U+0020..007E. */",
             f"#ifndef {guard}", f"#define {guard}",
             f"static const unsigned char {symbol}[] = {{"]
    lines += ["    " + ",".join(str(b) for b in data[i:i + 20]) + ","
              for i in range(0, len(data), 20)]
    lines += ["};", "#endif", ""]
    (ROOT / f"core/font_{symbol}.h").write_text("\n".join(lines), encoding="ascii")
    print(f"{name}: {len(data):,} bytes (weight {weight}, width {width})")


if __name__ == "__main__":
    bake("Saira-Bold", "saira_bold_ttf", 700, 100)
    bake("SairaCondensed-SemiBold", "saira_condensed_ttf", 600, 75)
