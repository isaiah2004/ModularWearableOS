/* Reproduce nos/ui_arc_trig.h using the original mask builder's float inputs.
 * gcc -O2 tools/arc_trig_table.c -o build/arc_trig_table.exe -lm
 * build/arc_trig_table.exe > nos/ui_arc_trig.h
 * This generator does no device IO. */
#include <math.h>
#include <stdio.h>
#include <string.h>
#ifdef _WIN32
#include <windows.h>
#endif
static void literal(float x)
{
    char buf[64];
    snprintf(buf,sizeof buf,"%.9g",(double)x);
    fputs(buf,stdout);
    if(!strchr(buf,'.') && !strchr(buf,'e'))fputs(".0",stdout);
    putchar('f');
}
int main(void)
{
#ifdef _WIN32
    SetErrorMode(SEM_FAILCRITICALERRORS | SEM_NOGPFAULTERRORBOX | SEM_NOOPENFILEERRORBOX);
#endif
    puts("/* Generated by tools/arc_trig_table.c; old float angle*2*RAD sinf/cosf. */");
    puts("static const float arc_trig[181][2] = {");
    for(int q=0;q<=180;q++) {
        float a=q*2*0.01745329251994329577f;
        fputs("    {",stdout); literal(sinf(a)); fputs(", ",stdout);
        literal(cosf(a)); puts("},");
    }
    puts("};");
    return 0;
}
